import asyncio, sys
from playwright.async_api import async_playwright
OUT = sys.argv[1] if len(sys.argv) > 1 else 'shots'
async def main():
    import os; os.makedirs(OUT, exist_ok=True)
    async with async_playwright() as p:
        b = await p.chromium.launch(args=["--use-gl=swiftshader","--enable-unsafe-swiftshader"])
        ctx = await b.new_context(viewport={"width":412,"height":915}, device_scale_factor=2, is_mobile=True, has_touch=True)
        pg = await ctx.new_page()
        errs=[]
        pg.on("pageerror", lambda e: errs.append("PAGEERROR "+str(e)))
        pg.on("console", lambda m: errs.append(m.type+" "+m.text) if m.type in ("error","warning") and "GPU stall" not in m.text and "swiftshader" not in m.text.lower() else None)
        await pg.goto("file:///home/claude/dfm/www/index.html"); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=f"{OUT}/01-onboarding.png")
        for i in range(3):
            await pg.click(".modal .btn.primary"); await pg.wait_for_timeout(250)
        await pg.wait_for_timeout(600)
        await pg.screenshot(path=f"{OUT}/02-moteur.png")
        await pg.evaluate("document.querySelector('#side-panel').scrollTop=500"); await pg.wait_for_timeout(200)
        await pg.screenshot(path=f"{OUT}/03-moteur-scroll.png")
        await pg.tap("#tabbtn-simulation"); await pg.wait_for_timeout(400)
        await pg.tap("#tab-simulation .seg button:has-text('Manuel')")
        await pg.tap("#tab-simulation >> text=Décoller"); await pg.wait_for_timeout(2500)
        # manche droit vers l'avant
        box = await pg.locator("#stick-right").bounding_box()
        cx, cy = box["x"]+box["width"]/2, box["y"]+box["height"]/2
        await pg.mouse.move(cx, cy); await pg.mouse.down(); await pg.mouse.move(cx, cy-40, steps=5); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=f"{OUT}/04-vol-manches.png")
        await pg.mouse.up()
        print("sim:", (await pg.inner_text("#tab-simulation .kpis")).replace("\n"," "))
        await pg.tap("#tab-simulation .seg button:has-text('Points')"); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=f"{OUT}/05-vol-points.png")
        await pg.tap("#tabbtn-ai"); await pg.wait_for_timeout(300)
        await pg.tap("#tab-ai >> text=Lancer l'entraînement"); await pg.wait_for_timeout(8000)
        await pg.screenshot(path=f"{OUT}/06-ia.png")
        await pg.tap("#tab-ai >> text=Mettre en pause")
        await pg.tap("#tabbtn-motherboard"); await pg.wait_for_timeout(800)
        await pg.screenshot(path=f"{OUT}/07-carte.png")
        await pg.tap("#tabbtn-production"); await pg.wait_for_timeout(800)
        await pg.screenshot(path=f"{OUT}/08-bom.png")
        await pg.tap("#tabbtn-lab"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=f"{OUT}/09-labo-vide.png")
        await pg.tap("text=PPO standard"); await pg.wait_for_timeout(400)
        await pg.screenshot(path=f"{OUT}/10-labo-config.png")
        await pg.tap(".lab-main > .seg button:has-text('Entraînement')")
        await pg.tap("#tab-lab >> text=Lancer l'entraînement"); await pg.wait_for_timeout(6000)
        await pg.screenshot(path=f"{OUT}/11-labo-train.png")
        await pg.tap(".lab-back"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=f"{OUT}/12-labo-liste.png")
        await pg.tap("#btn-menu"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=f"{OUT}/13-menu.png")
        await pg.tap("text=Confidentialité"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=f"{OUT}/14-confidentialite.png")
        sw = await pg.evaluate("[document.documentElement.scrollWidth, innerWidth, document.documentElement.scrollHeight, innerHeight]")
        print("dims", sw)
        # paysage
        await pg.set_viewport_size({"width":915,"height":412}); await pg.keyboard.press("Escape"); await pg.wait_for_timeout(300)
        await pg.tap("#tabbtn-simulation"); await pg.wait_for_timeout(1200)
        await pg.screenshot(path=f"{OUT}/15-paysage.png")
        print("\n".join(errs[:20]))
        await b.close()
asyncio.run(main())
